import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { LEGAL, LEGAL_CONTENT } from './legal-content.mjs';

const root = new URL('../', import.meta.url);
const escape = value => String(value).replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const file = (kind, language) => kind + (language === 'en' ? '-en' : '') + '.html';
for (const [language, content] of Object.entries(LEGAL_CONTENT)) {
  for (const kind of ['privacy', 'terms']) {
    const title = content[kind + 'Title'];
    const sections = content[kind];
    const opposite = language === 'en' ? 'ja' : 'en';
    const nav = `<a href="./index.html">${escape(content.back)}</a><a href="./${file(kind === 'privacy' ? 'terms' : 'privacy', language)}">${escape(content[kind === 'privacy' ? 'termsTitle' : 'privacyTitle'])}</a><a href="./${file(kind, opposite)}" lang="${opposite}" hreflang="${opposite}">${escape(content.language)}</a>`;
    const references = kind === 'privacy' ? `<aside aria-label="${language === 'ja' ? '外部サービスの方針' : 'Provider policies'}"><h2>${language === 'ja' ? '外部サービスの方針' : 'Provider policies'}</h2><ul>
      <li><a href="https://policies.google.com/privacy">Google Privacy Policy</a></li>
      <li><a href="https://developers.google.com/terms/api-services-user-data-policy">Google API Services User Data Policy (Limited Use)</a></li>
      <li><a href="https://www.cloudflare.com/privacypolicy/">Cloudflare Privacy Policy</a></li>
      <li><a href="https://myaccount.google.com/connections">${language === 'ja' ? 'Googleアカウントの接続・アクセス許可' : 'Google Account connections and permissions'}</a></li>
    </ul></aside>` : '';
    const html = `<!doctype html>
<!-- Generated by scripts/generate-legal-pages.mjs; edit scripts/legal-content.mjs. -->
<html lang="${language}">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="${escape('BookReader — ' + title + ' / ' + LEGAL.operator)}">
<title>${escape(title)} | BookReader</title><link rel="stylesheet" href="./assets/css/26-legal.css">
<link rel="alternate" hreflang="ja" href="./${file(kind, 'ja')}"><link rel="alternate" hreflang="en" href="./${file(kind, 'en')}">
</head>
<body class="legal-page"><a class="legal-skip" href="#legal-content">${language === 'ja' ? '本文へ移動' : 'Skip to content'}</a>
<header><p class="legal-brand">BookReader · ${escape(LEGAL.operator)}</p><nav aria-label="${language === 'ja' ? 'ページ案内' : 'Page navigation'}">${nav}</nav></header>
<main id="legal-content"><h1>${escape(title)}</h1><p class="legal-updated">${escape(content.updated)}: <time datetime="${LEGAL.updated}">${LEGAL.updated}</time></p><p>${escape(content[kind + 'Intro'])}</p>
<nav class="legal-toc" aria-label="${escape(content.contents)}"><h2>${escape(content.contents)}</h2><ol>${sections.map((section, index) => `<li><a href="#section-${index + 1}">${escape(section.title.replace(/^\d+\. /, ''))}</a></li>`).join('')}</ol></nav>
${sections.map((section, index) => `<section aria-labelledby="section-${index + 1}"><h2 id="section-${index + 1}">${escape(section.title)}</h2>${section.paragraphs.map(paragraph => `<p>${escape(paragraph)}</p>`).join('\n')}</section>`).join('\n')}
<section class="legal-contact"><h2>${escape(content.contact)}</h2><p>${escape(LEGAL.operator)}<br><a href="mailto:${escape(LEGAL.email)}">${escape(LEGAL.email)}</a></p></section>${references}
</main><footer><nav aria-label="${language === 'ja' ? 'ページ案内' : 'Page navigation'}">${nav}</nav></footer></body></html>
`;
    const target = new URL(file(kind, language), root);
    await writeFile(target, html, 'utf8');
    console.log('Generated ' + fileURLToPath(target));
  }
}
